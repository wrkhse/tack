#!/usr/bin/env node
// The Homebrew formula for a release, rendered from its SHA256SUMS:
//
//   node scripts/homebrew.mjs 0.3.0-rc.1 SHA256SUMS > Formula/tack.rb
//
// Every target's checksum comes from the same run that built the tarballs,
// so the formula is generated, never edited by hand.

import { readFileSync } from "node:fs"
import { resolve } from "node:path"
import { fileURLToPath } from "node:url"

const REPOSITORY = "https://github.com/wrkhse/tack"

/** Homebrew's OS and CPU blocks for each target, in the order they render. */
const PLATFORMS = [
  { os: "macos", cpu: "arm", target: "aarch64-apple-darwin" },
  { os: "macos", cpu: "intel", target: "x86_64-apple-darwin" },
  { os: "linux", cpu: "intel", target: "x86_64-unknown-linux-gnu" },
]

/** `SHA256SUMS` as a map from file name to checksum. */
export function parseSums(text) {
  const sums = new Map()

  for (const line of text.split("\n").filter((line) => line.trim() !== "")) {
    const match = line.match(/^([0-9a-f]{64})  (\S+)$/)

    if (!match) throw new Error(`not a SHA256SUMS line: ${line}`)
    if (sums.has(match[2])) throw new Error(`duplicate SHA256SUMS entry: ${match[2]}`)

    sums.set(match[2], match[1])
  }

  return sums
}

/** The tarball name for one release and Rust target. */
function tarballName(release, target) {
  return `tack-${release}-${target}.tar.gz`
}

export function formula(release, sums) {
  if (!/^\d+\.\d+\.\d+(?:-rc\.\d+)?$/.test(release)) {
    throw new Error(`a formula needs a release version, not ${release}`)
  }

  const expected = PLATFORMS.map(({ target }) => tarballName(release, target))

  if (sums.size !== expected.length || expected.some((name) => !sums.has(name))) {
    throw new Error(`SHA256SUMS must contain exactly ${expected.length} tarballs for ${release}`)
  }

  const render = (platform, indent) => {
    const name = tarballName(release, platform.target)

    return [
      `${indent}url "${REPOSITORY}/releases/download/v${release}/${name}"`,
      `${indent}sha256 "${sums.get(name)}"`,
    ].join("\n")
  }

  const macos = PLATFORMS.filter(({ os }) => os === "macos")
    .map((platform) => [`    on_${platform.cpu} do`, render(platform, "      "), "    end"].join("\n"))
    .join("\n")

  const linux = PLATFORMS.filter(({ os }) => os === "linux")
    .map((platform) => render(platform, "    "))
    .join("\n")

  // Ruby interpolation stays literal: JS must not evaluate #{bin} or ${version}.
  const testLine = '    assert_match "tack ${version}", shell_output("#{bin}/tack --version")'

  return `# Generated by scripts/homebrew.mjs in ${REPOSITORY} for each release.
# Do not edit by hand.
class Tack < Formula
  desc "Rust CLI and daemon for running one Luau plugin in every agent"
  homepage "${REPOSITORY}"
  version "${release}"
  license "MIT"

  on_macos do
${macos}
  end

  on_linux do
${linux}
  end

  def install
    bin.install "tack", "tack-daemon"
  end

  test do
${testLine}
  end
end
`
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const [release, sumsPath] = process.argv.slice(2)

  if (!release || !sumsPath) throw new Error("usage: homebrew.mjs VERSION SHA256SUMS")

  process.stdout.write(formula(release, parseSums(readFileSync(sumsPath, "utf8"))))
}
