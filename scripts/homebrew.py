#!/usr/bin/env python3
"""Render the Homebrew formula for a release from its SHA256SUMS.

Usage:

    python3 scripts/homebrew.py VERSION SHA256SUMS > Formula/tack.rb

Every target's checksum comes from the same run that built the tarballs, so
the formula is generated, never edited by hand.
"""

import re
import sys
from pathlib import Path

REPOSITORY = "https://github.com/wrkhse/tack"
DESC = "Rust CLI and daemon for running one Luau plugin in every agent"

# Homebrew's OS and CPU blocks for each target, in the order they render.
PLATFORMS = (
    ("macos", "arm", "aarch64-apple-darwin"),
    ("macos", "intel", "x86_64-apple-darwin"),
    ("linux", "intel", "x86_64-unknown-linux-gnu"),
)

RELEASE_RE = re.compile(r"^\d+\.\d+\.\d+(?:-rc\.\d+)?$")
SUM_LINE_RE = re.compile(r"^([0-9a-f]{64})  (\S+)$")

# Ruby interpolation stays literal: Python must not touch #{version} or
# #{bin}. These are plain strings, never f-strings.
TEST_LINE = (
    '    assert_match "tack #{version}", '
    'shell_output("#{bin}/tack --version")'
)


def parse_sums(text):
    """Return SHA256SUMS text as a dict from file name to checksum."""
    sums = {}

    for line in text.splitlines():
        if not line.strip():
            continue

        match = SUM_LINE_RE.match(line)
        if match is None:
            raise ValueError(f"not a SHA256SUMS line: {line}")

        checksum, name = match.groups()
        if name in sums:
            raise ValueError(f"duplicate SHA256SUMS entry: {name}")

        sums[name] = checksum

    return sums


def tarball_name(release, target):
    """Return the release tarball name for one Rust target."""
    return f"tack-{release}-{target}.tar.gz"


def formula(release, sums):
    """Render the Ruby formula for a validated release and its checksums."""
    if RELEASE_RE.match(release) is None:
        raise ValueError(f"a formula needs a release version, not {release}")

    expected = [tarball_name(release, target) for _, _, target in PLATFORMS]

    if set(sums) != set(expected):
        raise ValueError(
            f"SHA256SUMS must contain exactly {len(expected)} tarballs "
            f"for {release}"
        )

    def render(platform, indent):
        _, _, target = platform
        name = tarball_name(release, target)
        url = f"{REPOSITORY}/releases/download/v{release}/{name}"

        return [
            f'{indent}url "{url}"',
            f'{indent}sha256 "{sums[name]}"',
        ]

    macos = []
    linux = []

    for os_name, cpu, target in PLATFORMS:
        platform = (os_name, cpu, target)

        if os_name == "macos":
            macos.append(f"    on_{cpu} do")
            macos.extend(render(platform, "      "))
            macos.append("    end")
        else:
            linux.append(f"    on_{cpu} do")
            linux.extend(render(platform, "      "))
            linux.append("    end")

    lines = [
        f"# Generated by scripts/homebrew.py in {REPOSITORY}",
        "# for each release. Do not edit by hand.",
        "class Tack < Formula",
        f'  desc "{DESC}"',
        f'  homepage "{REPOSITORY}"',
        '  license "MIT"',
        "",
        "  on_macos do",
        *macos,
        "  end",
        "",
        "  on_linux do",
        *linux,
        "  end",
        "",
        "  def install",
        '    bin.install "tack", "tack-daemon", "tack-hook"',
        "  end",
        "",
        "  test do",
        TEST_LINE,
        "  end",
        "end",
    ]

    return "\n".join(lines) + "\n"


def main(argv=None):
    args = sys.argv[1:] if argv is None else argv

    if len(args) != 2:
        raise SystemExit("usage: python3 scripts/homebrew.py VERSION SHA256SUMS")

    release, sums_path = args
    text = Path(sums_path).read_text(encoding="utf-8")

    sys.stdout.write(formula(release, parse_sums(text)))


if __name__ == "__main__":
    main()
